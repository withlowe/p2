// Generates *-src.js: the browser files as strings, so the Worker can serve
// them without ever running them, plus a build id derived from their content.
//
// The build id is what makes long caching safe. Without it the HTML shell
// (never cached) can load a year-old app.js (cached hard), and a deploy
// appears to do nothing.
//
//   node tools/bundle.mjs
import { readFileSync, writeFileSync } from "node:fs";
import { createHash } from "node:crypto";

const hash = createHash("sha256");

for (const name of ["crypto", "app", "words"]) {
  const src = readFileSync(new URL(`../${name}.js`, import.meta.url), "utf8");
  hash.update(src);
  writeFileSync(
    new URL(`../${name}-src.js`, import.meta.url),
    `// GENERATED by tools/bundle.mjs — edit ${name}.js, not this file.\n` +
      "export default " + JSON.stringify(src) + ";\n"
  );
  console.log(`${name}-src.js written (${src.length} bytes)`);
}

const build = hash.digest("hex").slice(0, 10);
writeFileSync(
  new URL("../build-src.js", import.meta.url),
  "// GENERATED by tools/bundle.mjs — the content hash of the browser files.\n" +
    `export default ${JSON.stringify(build)};\n`
);
console.log(`build ${build}`);
